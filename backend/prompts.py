def build_segment_prose_prompt(
    events: list, choice_texts: tuple[str, str] | None, *, include_rules: bool = True,
) -> str:
    """Standalone template by default; runtime caches rules in the system prefix."""
    events_list = "\n".join(f"  {i+1}. {event_prompt(e)}" for i, e in enumerate(events))
    legacy = any(not isinstance(e, dict) or e.get("v") not in (2, 3) for e in events)
    if choice_texts:
        choice_instruction = (
            "Подведи последнюю сцену к уже заданному выбору: "
            + json.dumps(list(choice_texts), ensure_ascii=False)
            + ". В ответе выбор не повторяй: его покажет игра."
        )
    else:
        choice_instruction = "Этот участок не содержит выбора: реализуй список до конца."
    if events and isinstance(events[-1], dict) and events[-1].get("ending") in ("death", "failure", "victory"):
        choice_instruction += (
            "\nЭТО ЗАВЕРШАЮЩИЙ СЕГМЕНТ ИСТОРИИ. Покажи действия, которыми достигнут "
            "заданный исход. Главный конфликт к последней сцене разрешён; не заканчивай "
            "обещанием будущей встречи с основной угрозой или ещё предстоящей развязкой. "
            "Не меняй заданный исход на победу: поражение и смерть тоже финалы."
        )
    metadata = (PROSE_RULES + MODERN_PROSE_METADATA) if include_rules else ""
    if legacy:
        metadata += LEGACY_PROSE_METADATA + SCENE_LOCATIONS_PROMPT
        if any(not isinstance(e, dict) for e in events):
            metadata += SCENE_EFFECTS_PROMPT
    return SEGMENT_PROSE_PROMPT.format(
        events_list=events_list, choice_instruction=choice_instruction,
        metadata_instruction=metadata, scene_count=len(events),
    )


