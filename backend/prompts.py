def _phase_at(scene: int, target_length: int) -> str:
    """Чистая функция определения фазы по номеру сцены — используется и
    для одной точки (совместимость), и как строительный блок для диапазона."""
    ratio = scene / target_length if target_length else 0
    if scene + 1 >= target_length:
        return "финал"
    if ratio < 0.3:
        return "завязка"
    if ratio < 0.7:
        return "развитие"
    return "кульминация"


