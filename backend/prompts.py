def build_segment_plan_directive(
    plan: dict | None, start_scene: int, ceiling_scene: int, target_length: int,
    segment_index: int | None = None,
) -> str:
    """
    Сегмент может охватывать НЕСКОЛЬКО фаз разом — например, сегмент,
    ведущий к первому окну выбора (скажем, сцены 1-11 из 30), частично уже
    лежит в фазе "развитие" (граница на сцене 9), не только в "завязке". Если
    показать модели только одну фазу — вторая половина сегмента писалась
    бы без единого ориентира на то, что там должно происходить. Здесь —
    все переломные точки, чьи фазы затронуты диапазоном [start_scene,
    ceiling_scene], не одна и не все до конца истории.
    """
    if not plan or not isinstance(plan, dict):
        return ""


    segments = plan.get("segments")
    if isinstance(segments, list) and segments:
        if segment_index is None:
            segment_index = sum(start_scene > end for _, end in choice_windows(target_length))
        if not 0 <= segment_index < len(segments):
            return ""
        return (
            f"\n[ЗАГОТОВКА СЕГМЕНТА {segment_index + 1} ИЗ {len(segments)}]\n"
            + json.dumps(segments[segment_index], ensure_ascii=False, separators=(",", ":"))
            + "\nЭто потенциальные места и крупные события. Адаптируй их к реальному выбору "
              "и свершившимся событиям; не заставляй героя выполнять отвергнутое действие. "
              "Конкретику задай только в новых событиях этого сегмента.\n"
        )

    turning_points = plan.get("turning_points")
    if not isinstance(turning_points, list) or not turning_points:
        return ""

    touched_phases = {_phase_at(start_scene, target_length), _phase_at(ceiling_scene, target_length)}
    order = ["завязка", "развитие", "кульминация", "финал"]
    # Если сегмент перепрыгивает через фазу целиком (не должно случаться
    # при текущих окнах, но на всякий случай) — включаем и промежуточные.
    idxs = sorted(order.index(p) for p in touched_phases if p in order)
    if len(idxs) == 2:
        touched_phases |= set(order[idxs[0]:idxs[1] + 1])

    relevant = [p for p in turning_points if isinstance(p, dict) and p.get("phase") in touched_phases]
    if not relevant:
        return ""

    premise = plan.get("premise", "")
    lines = "\n".join(
        f"  - «{p.get('phase', '')}»: {p.get('event', '')} "
        f"(уместный тип решения: {p.get('choice_shape', '')})"
        for p in relevant
    )
    return (
        f"\n[ПЛАН ИСТОРИИ]\nОбщее видение: {premise}\n"
        f"Этот участок затрагивает следующие фазы плана, по порядку:\n{lines}\n"
    )


CHOICE_WINDOW_RADIUS = 2  # окно ±2 вокруг границы фазы = 5 сцен


def choice_window_count(target_length: int) -> int:
    """
    Сколько окон выбора в истории данной длины.

    Не константа, потому что от этого напрямую зависит длина ОДНОГО
    сегмента — а сегмент пишется единственным связным вызовом, и чем он
    длиннее, тем выше риск, что модель к концу потеряет нить того, что
    сама написала в начале. Живым прогоном подтверждена связность на
    сегментах примерно до 23 сцен; больше — непроверенная территория.

    Отсюда пороги: длинная история (>60 сцен) получает 3 окна, иначе
    отдельный сегмент вышел бы за 30+ сцен. Средняя обходится двумя.

    Верхняя граница — сколько окон физически помещается без пересечений:
    каждое занимает 2*RADIUS+1 сцен, и между ними нужен зазор. Без этого
    на короткой истории (валидация допускает от 3 сцен) окна совпали бы
    целиком, а _segment_after ищет окно ПО ЗНАЧЕНИЮ — нашла бы первое
    вместо второго и построила бы неверную структуру дерева.
    """
    window_span = 2 * CHOICE_WINDOW_RADIUS + 1
    # n окон делят историю на n+1 участков; чтобы окна не слиплись, каждый
    # интервал между центрами должен быть строго больше размаха окна.
    # Отсюда: target_length/(n+1) > window_span  =>  n < length/span - 1
    max_fitting = max(1, int(target_length / window_span) - 1)
    desired = 3 if target_length > 60 else 2
    return min(desired, max_fitting)


def choice_windows(target_length: int) -> tuple[tuple[int, int], ...]:
    """
    Границы фаз, равномерно распределённые по длине истории, каждая
    расширена в окно из 5 сцен (CHOICE_WINDOW_RADIUS по обе стороны).
    Модель сама решает, на КАКОЙ сцене внутри окна разместить настоящий
    выбор — не жёсткая точная позиция (это было бы искусственно), но и не
    полная свобода (тогда мы не знали бы заранее длину сегмента, который
    просим сгенерировать одним вызовом).

    Число окон зависит от длины (см. choice_window_count). При двух окнах
    они встают на 33% и 67%, при трёх — на 25%, 50% и 75%: в обоих случаях
    участки между ними примерно равны, а не перекошены.
    """
    n = choice_window_count(target_length)

    # Окна ставятся на ГРАНИЦЫ ФАЗ, а не просто равномерно по длине: выбор
    # осмысленнее там, где сюжет и так переламывается (завязка -> развитие,
    # развитие -> кульминация), чем посреди ровного участка. Доли совпадают
    # с порогами в pacing_hint — иначе развилка попадала бы в середину фазы,
    # где ей нечего переламывать.
    phase_marks = (0.30, 0.60, 0.85)
    fractions = phase_marks[:n] if n <= len(phase_marks) else [
        (i + 1) / (n + 1) for i in range(n)
    ]

    windows = []
    for frac in fractions:
        center = round(target_length * frac)
        windows.append((
            max(1, center - CHOICE_WINDOW_RADIUS),
            min(target_length - 1, center + CHOICE_WINDOW_RADIUS),
        ))
    return tuple(windows)


