SEGMENT_EVENTS_PROMPT = """ЗАДАЧА: спланировать один сегмент событий, без прозы.
{state_block}
{plan_directive}
{segment_instruction}
Каждое событие — один значимый шаг к развилке/исходу, без сцен-заполнителей.
{event_contract}
"""

def build_segment_events_prompt(
    state_block: str, plan_directive: str, start_scene: int, ceiling_scene: int,
    window: tuple[int, int] | None,
) -> str:
    """
    Дешёвый этап построения — только список событий, без прозы. Прозу
    для этого участка допишет build_segment_prose_prompt, но только если
    игрок реально дойдёт до него — на этапе построения всего дерева она
    не нужна для веток, которые может никто и не увидит.
    """
    max_scenes = ceiling_scene - start_scene + 1
    if window is None:
        instruction = (
            f"ЭТО ФИНАЛЬНЫЙ УЧАСТОК: максимум {max_scenes} событий, без новых выборов. "
            "Разреши главный конфликт конкретными действиями до ending. "
            "Второстепенное сократи; не растягивай развязку повторными отчётами."
        )
    else:
        w_start, w_end = window
        instruction = (
            f"Номера событий истории {start_scene}..{w_end}, максимум {max_scenes} событий. "
            f"Размести одну развилку в окне {w_start}..{w_end}: ровно 2 действия игрока. "
            "До окна выборов нет. Событие с choices — последнее; продолжений не планируй."
        )
    return SEGMENT_EVENTS_PROMPT.format(
        state_block=state_block, plan_directive=plan_directive,
        segment_instruction=instruction, event_contract=EVENT_CONTRACT,
    )


